  'أسئلة «وين» و«شلون» تجيبها عادي.';

/** ما يرسله الهاتف لـ«إرشاد فقط» (guideLevel في Dart): الشاشات والحاسبة وحالة التجهيز. لا بيانات محل فيها. */
export const GUIDE_LEVEL_TOOLS = new Set(['ui_describe', 'ui_navigate', 'ui_highlight', 'ui_guide', 'ui_start_tour', 'calc', 'setup_status']);
export function isGuideOnly(tools: string[]): boolean {
  return tools.length > 0 && tools.every((t) => GUIDE_LEVEL_TOOLS.has(t));
}

export const SCREEN_ITEM_KINDS = new Set(['oil_card', 'product', 'customer', 'invoice']);
export type ScreenItem = { kind: 'oil_card' | 'product' | 'customer' | 'invoice'; id: number };

const SCREEN_ITEM_HINT: Record<ScreenItem['kind'], (id: number) => string> = {
  oil_card: (id) => `بطاقة غيار (oil_card_find بـ card_id=${id})`,
  product: (id) => `منتج (product_detail بـ product_id=${id})`,
  customer: (id) => `زبون (car_history بـ customer_id=${id})`,
  invoice: (id) => `فاتورة رقم ${id} (لا أداة لتفاصيلها: وجّهه لشاشتها المفتوحة)`,
};

export type PromptContext = {
  isOwner: boolean;
  roleKey: string;
  guideOnly: boolean;
  routeId: string | null;
  routeTitle?: string | null;
  branchName?: string | null;
  /** العنصر المفتوح على الشاشة. «هذا/هنا» تعنيه. */
  screenItem?: ScreenItem | null;
  economy: boolean;
  now?: Date;
};

/** الوقت بتوقيت بغداد بصيغة مقروءة. */
export function baghdadNow(now: Date = new Date()): string {
  const bg = new Date(now.getTime() + 3 * 3600_000);
  const days = ['الأحد', 'الاثنين', 'الثلاثاء', 'الأربعاء', 'الخميس', 'الجمعة', 'السبت'];
  const p = (n: number) => String(n).padStart(2, '0');
  return `${days[bg.getUTCDay()]} ${bg.getUTCFullYear()}-${p(bg.getUTCMonth() + 1)}-${p(bg.getUTCDate())} ${p(bg.getUTCHours())}:${p(bg.getUTCMinutes())}`;
}

export function buildContextMessage(c: PromptContext): string {
  const role = c.isOwner ? ROLE_LABELS.owner : c.guideOnly ? ROLE_LABELS.guide_only : ROLE_LABELS.staff;
  const lines = [
    `المستخدم الحالي: ${role}.`,
    `الشاشة المفتوحة: ${c.routeTitle || c.routeId || 'غير معروفة'}.`,
    `الوقت في بغداد: ${baghdadNow(c.now)}.`,
  ];
  if (!c.isOwner && c.guideOnly) lines.push(GUIDE_ONLY_RULE);
  if (c.branchName) lines.push(`الفرع: ${c.branchName}.`);
  if (c.screenItem) {
    lines.push(`العنصر المفتوح على الشاشة: ${SCREEN_ITEM_HINT[c.screenItem.kind](c.screenItem.id)}. «هذا/هنا/هالبطاقة» تعنيه؛ اجلب تفاصيله بالأداة المذكورة قبل الجواب.`);
  }
  if (c.economy) lines.push('وضع التوفير مفعّل: اختصر الجواب أكثر، وتجنب الخطوات غير الضرورية.');
  return lines.join('\n');
}

/**
 * يبني رسائل الطلب: الثابت، ثم الدروس، ثم السياق، ثم المحادثة.
 * المحادثة تأتي من الهاتف وقد قُصّت وفُحصت في index.ts.
 */
export function buildMessages(
  ctx: PromptContext,
  ruleLessons: string[],
  conversation: Record<string, unknown>[],
  knowledge = '',
): Record<string, unknown>[] {
  const msgs: Record<string, unknown>[] = [{ role: 'system', content: STATIC_SYSTEM }];
  if (ruleLessons.length > 0) {
    msgs.push({
      role: 'system',
      content: 'قواعد تعلّمها المساعد من استعمال المحلات:\n' + ruleLessons.map((l) => `- ${l}`).join('\n'),
    });
  }
  msgs.push({ role: 'system', content: buildContextMessage(ctx) });
  if (knowledge) msgs.push({ role: 'system', content: knowledge });
  return [...msgs, ...conversation];
}

/**
 * يفصل سطر الاقتراحات عن نص الجواب.
 * الصيغة: [[س1 | س2 | س3]]. أي شيء بعد [[ لا يُعرض.
 */
export function splitFollowups(text: string): { text: string; followups: string[] } {
  const i = text.indexOf(FOLLOWUPS_OPEN);
  if (i < 0) return { text: text.trim(), followups: [] };
  const body = text.slice(i + 2);
  const end = body.indexOf(']]');
  const inner = end >= 0 ? body.slice(0, end) : body;
  const followups = inner
    .split('|')
    .map((s) => s.trim())
    .filter((s) => s.length > 0 && s.length <= 60)
    .slice(0, 3);
  return { text: text.slice(0, i).trim(), followups };
}

/**
 * مرشّح بث: يمرر النص حتى يظهر «[[» ثم يحجب الباقي.
 * يحتفظ بآخر حرف إن كان «[» حتى يعرف إن كان بداية العلامة.
 */
export class FollowupStreamFilter {
  private held = '';
  private blocked = false;

  push(delta: string): string {
    if (this.blocked) return '';
    const s = this.held + delta;
    const i = s.indexOf(FOLLOWUPS_OPEN);
    if (i >= 0) {
      this.blocked = true;
      this.held = '';
      return s.slice(0, i);
    }
    if (s.endsWith('[')) {
      this.held = '[';
      return s.slice(0, -1);
    }
    this.held = '';
    return s;
  }

  flush(): string {
    if (this.blocked) return '';
    const h = this.held;
    this.held = '';
    return h;
  }
}
