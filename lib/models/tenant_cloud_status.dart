/// نتيجة فحص اكتمال حساب Naboo على السحابة (`owner_auth_secrets`).
///
/// يفصل «لا يوجد حساب» عن «تعذر الاتصال» حتى لا يُعامل انقطاع الشبكة
/// كعدم وجود حساب (كان يسبب رسالة «أنشئ حساباً جديداً» الخاطئة).
enum TenantCloudStatus {
  /// جوال + PIN موجودان في `owner_auth_secrets` — الحساب مكتمل.
  complete,

  /// جلسة سحابية موجودة لكن لا سر PIN — حساب جديد/غير مكتمل.
  incomplete,

  /// فشل الوصول للسحابة (شبكة/مهلة) — لا يمكن الحسم.
  networkError,
}
