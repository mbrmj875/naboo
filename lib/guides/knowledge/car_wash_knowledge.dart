/// معرفة تشغيلية لبطاقة غسيل السيارات على الرئيسية ومسارات التفعيل.
library;

abstract final class CarWashKnowledge {
  static const packSnippet = '''
غسيل السيارات في نابو (مرتبط بعمودي غيار الزيت على الرئيسية):

ماذا ترى على الرئيسية؟
- تحت زر «غيار زيت جديد» يظهر زر ذهبي: «غسيل السيارات» وعنوانه الفرعي «بطاقة غسيل سريعة».
- الضغط عليه يفتح شاشة «بطاقة غسيل سيارة»: لوحة، عميل، اختيار أنواع الغسيل من الكتالوج، المبلغ، ثم حفظ وبيع.

كيف تُظهر أو تُخفي زر غسيل السيارات؟
1) افتح الإعدادات من القائمة.
2) ادخل «تخصيص الشاشة الرئيسية».
3) تحت «أزرار إضافية» بدّل مفتاح «زر غسيل السيارات».
- عند الإيقاف: يختفي الزر من الرئيسية لهذا الموظف/الجهاز حسب تفضيل الواجهة.
- عند التشغيل: يظهر تحت «غيار زيت جديد» إن كان عمودي غيار الزيت مفعّلاً للمحل.
ملاحظة: إخفاء الزر ≠ حذف أنواع الغسيل أو الفواتير السابقة؛ فقط يخفي الاختصار من الرئيسية.

كيف تضيف/تعدّل أنواع الغسيل وأسعارها؟
- من سجل غيارات الزيت → «أنواع الغسيل وأسعارها»، أو من داخل بطاقة الغسيل عبر إدارة الأنواع.
- لكل نوع: اسم + سعر بالفلس يُختار في البطاقة.

كيف تسجّل غسيل؟
1) الرئيسية → «غسيل السيارات».
2) أدخل اللوحة واسم/هاتف الزبون إن لزم.
3) اختر نوع/أنواع الغسيل من القائمة.
4) راجع الإجمالي والمدفوع ثم حفظ وبيع.

ما الذي لا يفعله المساعد؟
- لا يرسل أسعار حية أو حالة المفتاح الحقيقية للنموذج؛ يشرح المسار فقط.
- «إلغاء بطاقة غسيل» إن قصد المستخدم إخفاء الزر: استخدم تخصيص الرئيسية أعلاه. إن قصد حذف فاتورة/طلب سابق: من سجل الفواتير/الخدمات حسب صلاحياته — ليس من زر الرئيسية.
''';

  static String? matchSnippet(String normalizedQuestion) {
    final q = normalizedQuestion;
    if (q.contains('غسيل') ||
        q.contains('غسل') ||
        q.contains('car wash') ||
        q.contains('كار واش') ||
        q.contains('بطاقة غسيل') ||
        q.contains('انواع الغسيل') ||
        q.contains('أنواع الغسيل') ||
        (q.contains('اخفي') && q.contains('غسيل')) ||
        (q.contains('الغي') && q.contains('غسيل')) ||
        (q.contains('الغي') && q.contains('غسل')) ||
        (q.contains('اوقف') && q.contains('غسيل')) ||
        (q.contains('فعل') && q.contains('غسيل')) ||
        (q.contains('تفعيل') && q.contains('غسيل')) ||
        (q.contains('اظهار') && q.contains('غسيل')) ||
        ((q.contains('إخفاء') || q.contains('اخفاء')) && q.contains('غسيل'))) {
      return packSnippet.trim();
    }
    return null;
  }
}
