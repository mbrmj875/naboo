/// معرفة كتالوجات أسعار البطاقة مقابل المخزون.
library;

abstract final class OilCatalogKnowledge {
  static const packSnippet = '''
كتالوجات غيار الزيت (أسعار البطاقة) — ليست مخزون العائلات:
1) كتالوج الزيت واللزوجات: من بطاقة غيار زيت → زر إضافة بجانب اسم الزيت/اللزوجة. لإضافة ماركة ولزوجة وسعر بيع/لتر يُختار لاحقاً في البطاقة.
2) كتالوج الفلاتر: من البطاقة → قسم الإضافات → زر إضافة بجانب فلتر المحرك/الهواء/الكير، أو من شاشة الخدمات وأسعارها.
3) كتالوج الهيدروليك: من البطاقة → هيدروليك → زر إضافة لإضافة ماركة/درجة وسعر.
فرق مهم: كتالوج الأسعار على البطاقة ≠ إضافة منتج عائلة زيت/هيدروليك في شاشة المنتجات (المخزون) اللازم لخصم اللترات عند تفعيل صرف المخزون.
السعر الأساسي لتبديل الزيت يُضبط من شاشة «الخدمات وأسعارها» وليس من كتالوج الماركات.
''';

  static String? matchSnippet(String normalizedQuestion) {
    final q = normalizedQuestion;
    if (q.contains('كتالوج') ||
        q.contains('لزوج') ||
        q.contains('ماركه') ||
        q.contains('ماركة') ||
        q.contains('فلتر') ||
        q.contains('هيدروليك') ||
        q.contains('اضيف زيت') ||
        q.contains('أضيف زيت') ||
        q.contains('منتج زيت') ||
        q.contains('اسعار الزيت') ||
        q.contains('أسعار الزيت')) {
      return packSnippet.trim();
    }
    return null;
  }
}
