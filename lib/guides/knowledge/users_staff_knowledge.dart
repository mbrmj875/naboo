/// معرفة تشغيلية مفصّلة: الموظفون والمستخدمون والهويات والورديات.
library;

/// حزم معرفة ثابتة لوحدة المستخدمين (overview / menu / form / identity / shifts).
abstract final class UsersStaffKnowledge {
  /// نظرة عامة منظّمة — تُستخدم كمرجع أساسي.
  static const packSnippet = '''
وحدة «المستخدمين» في نابو — دليل كامل:

① أين تجدها؟
من الشريط السفلي اضغط «المستخدمين» — تفتح قائمة فرعية فيها ثلاثة أبواب:
1) إدارة المستخدمين — قائمة الموظفين وزر «مستخدم جديد».
2) ورديات الموظفين (أسبوع) — تقويم أسبوعي (سبت→جمعة) لأوقات الدخول والخروج.
3) هويات الموظفين — بطاقة هوية لكل موظف (باركود/QR + رمز وردية).

② ما الفائدة؟
- لكل موظف اسم ورمز PIN من 4 أرقام — دخول منفصل بدون مشاركة حساب المالك.
- يظهر في بوابة «من سيبدأ العمل؟» بعد ربط الجهاز بحساب المالك.
- يُربط بفتح/إغلاق الوردية، والصلاحيات (ماذا يرى من الشاشات)، وبطاقة الهوية.
- قفل الجلسة من الرئيسية يعيد لاختيار الحساب — وليس خروجاً نهائياً من السحابة.

③ مسار الدخول:
1) المالك يربط الجهاز (Google/بريد) مرة واحدة من تسجيل الدخول.
2) بوابة «من سيبدأ العمل؟» — اختيار الحساب + PIN.
3) المالك للرئيسية مباشرة؛ الموظف غالباً يفتح وردية ثم الرئيسية.

④ إضافة مستخدم جديد (مالك/مدير):
المستخدمين → إدارة المستخدمين → «مستخدم جديد» ثم:
- بيانات الموظف: الاسم الظاهر.
- رمز الدخول PIN: 4 أرقام + تأكيد (ليس رمزاً ضعيفاً مثل 1234).
- مستوى الصلاحية: محدود / كامل / تخصيص يدوي (صلاحيات تفصيلية).
- حفظ — يظهر في القائمة وفي بوابة الدخول؛ غالباً تُقترح بطاقة الهوية بعدها.
بديل: من بوابة «من سيبدأ العمل؟» بطاقة «مستخدم جديد» بعد PIN المالك.

⑤ هويات الموظفين:
قائمة الهويات → افتح بطاقة الموظف لعرض باركود/QR ورمز الوردية. من قائمة ⋮ على بطاقة المستخدم: «بطاقة الهوية». المالك/المدير قد يجدّد رمز الوردية عند الحاجة.

⑥ ورديات الموظفين (أسبوع):
تقويم من السبت للجمعة؛ أشرطة من وقت فتح الوردية إلى إغلاقها مع اسم موظف الوردية. تنقّل بين الأسابيع أو «هذا الأسبوع». الورديات تُنشأ عند فتح/إغلاق الوردية اليومي — هذه الشاشة للعرض والمتابعة.

⑦ أخطاء شائعة:
- لا يظهر في البوابة: PIN غير صالح أو الحساب معطّل.
- الموظف العادي لا يضيف مستخدمين — يحتاج مالك/مدير.
- قفل الجلسة ≠ حذف الحساب.
''';

  static const menuPack = '''
قائمة «المستخدمين» (الشريط السفلي):
اضغط أيقونة المستخدمين → تظهر ورقة سفلية بعنوان «المستخدمين» وفيها:
• إدارة المستخدمين — قائمة الحسابات المحلية + إضافة/تعديل/تعطيل + اختصار الهوية.
• ورديات الموظفين (أسبوع) — جدول أسبوعي لحضور الورديات.
• هويات الموظفين — بطاقات الهوية (باركود/QR).
اختر الباب المطلوب؛ «عرض الكل» إن وُجد يعيد للقائمة الكاملة.
''';

  static const addFormPack = '''
صفحة «مستخدم جديد» / «تعديل مستخدم» — تفاصيل الحقول:

1) بيانات الموظف:
- حقل «الاسم»: الاسم الذي يظهر في بوابة «من سيبدأ العمل؟» وفي الورديات والهويات.

2) رمز الدخول (PIN):
- 4 أرقام فقط؛ عند الإنشاء مطلوب مع «تأكيد رمز PIN».
- عند التعديل: اتركه فارغاً للإبقاء على الرمز الحالي، أو أدخل رمزاً جديداً مرتين.
- تجنّب الرموز السهلة (مثل 0000 أو 1234) — النظام يرفض الضعيف.
- هذا PIN لدخول الجهاز/اختيار الحساب — مختلف عن «رمز الوردية» في بطاقة الهوية.

3) مستوى الصلاحية (اختر واحداً):
- موظف محدود التخصيص: أساسي (نقطة بيع، عرض مخزون، صندوق…).
- موظف كامل التخصيص: كل الصلاحيات (تقارير، إدارة مخزون، عملاء، إعدادات…).
- تخصيص يدوي: تفتح «الصلاحيات التفصيلية» مجموعةً مجموعة لتفعيل ما يحتاجه فقط.

4) حفظ / إلغاء:
- «حفظ» ينشئ الحساب ويظهر في إدارة المستخدمين وبوابة الدخول.
- بعد الإنشاء قد تُفتح هوية الموظف مباشرة لطباعة/عرض البطاقة.
- «إلغاء» يغلق دون حفظ.

مسار الوصول: الشريط السفلي → المستخدمين → إدارة المستخدمين → زر «مستخدم جديد» (ذهبي أسفل الشاشة).
''';

  static const identityPack = '''
هويات الموظفين:
- الشاشة: المستخدمين → هويات الموظفين (أو من بطاقة مستخدم → ⋮ → بطاقة الهوية).
- كل موظف نشط له صف؛ اضغط للتوسيع وعرض بطاقة الهوية (اسم، باركود، QR، رمز وردية).
- الفائدة: تعريف الموظف عند الوردية أو الطباعة/المسح دون كشف PIN الدخول.
- تجديد رمز الوردية (للمالك/المدير): يولّد رمزاً جديداً ويجب تحديث البطاقة الموزّعة.
- لا يوجد موظفون؟ أضفهم أولاً من إدارة المستخدمين.
''';

  static const shiftsPack = '''
ورديات الموظفين (أسبوع):
- الشاشة: المستخدمين → ورديات الموظفين (أسبوع).
- عرض أسبوعي من السبت إلى الجمعة؛ داخل كل يوم محور زمني وأشرطة من الدخول إلى الخروج مع اسم موظف الوردية.
- أزرار الأسبوع السابق/التالي و«هذا الأسبوع».
- الورديات تُسجَّل عند فتح الوردية وإغلاقها في التشغيل اليومي — هنا للمتابعة والمراجعة وليس لإنشاء وردية يدوياً من هذه الشاشة.
- اسم موظف الوردية يأتي من الحساب الذي فُتحت به الوردية (بعد اختياره من «من سيبدأ العمل؟»).
''';

  static String? matchSnippet(String normalizedQuestion) {
    final q = normalizedQuestion;

    bool any(List<String> keys) {
      for (final k in keys) {
        if (q.contains(k)) return true;
      }
      return false;
    }

    if (any(const [
      'هويه',
      'هوية',
      'هويات',
      'بطاقه الهويه',
      'بطاقة الهوية',
      'باركود الموظف',
      'رمز الورديه',
      'رمز الوردية',
    ])) {
      return identityPack.trim();
    }

    if (any(const [
      'ورديات الموظف',
      'ورديه الموظف',
      'وردية الموظف',
      'جدول الورديات',
      'تقويم الورديات',
      'ورديات الاسبوع',
      'ورديات الأسبوع',
      'حضور الموظف',
    ])) {
      return shiftsPack.trim();
    }

    if (any(const [
      'مستخدم جديد',
      'صفحه الاضافه',
      'صفحة الإضافة',
      'نموذج المستخدم',
      'بيانات المستخدم',
      'رمز pin',
      'مستوى الصلاحيه',
      'مستوى الصلاحية',
      'تخصيص يدوي',
      'موظف محدود',
      'موظف كامل',
      'اضيف موظف',
      'أضيف موظف',
      'اضيف مستخدم',
      'أضيف مستخدم',
      'انشئ مستخدم',
      'أنشئ مستخدم',
    ])) {
      return addFormPack.trim();
    }

    if (any(const [
      'قائمه المستخدمين',
      'قائمة المستخدمين',
      'اداره المستخدمين',
      'إدارة المستخدمين',
      'القائمه الفرعيه',
      'القائمة الفرعية',
      'شريط المستخدمين',
    ])) {
      return menuPack.trim();
    }

    if (any(const [
      'موظف',
      'موظفين',
      'مستخدم',
      'مستخدمين',
      'من سيبدا',
      'من سيبدأ',
      'بوابه الموظف',
      'بوابة الموظف',
      'اختيار الحساب',
      'صلاحيات',
      'فايده الموظف',
      'فائدة الموظف',
    ])) {
      return packSnippet.trim();
    }

    return null;
  }
}
