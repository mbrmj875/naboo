/// معرفة تشغيلية مفصّلة: إضافة منتج جديد وحقول المخزون والتسعير.
library;

/// حزم معرفة ثابتة لوحدة المنتجات / إضافة منتج.
abstract final class InventoryProductKnowledge {
  static const overviewPack = '''
إضافة منتج جديد في نابو — نظرة عامة:

① أين؟
المخزون → قائمة المنتجات → «+ منتج جديد»، أو مباشرة «إضافة منتج جديد» من قائمة المخزون.

② بطاقة بيانات المنتج (الأهم أولاً):
- اسم المنتج: إلزامي — يظهر في البيع والبحث والفواتير.
- SKU: يُولَّد تلقائياً للعرض؛ لا حاجة لإدخاله.
- الوصف: اختياري مفيد للموظفين؛ ليس شرط البيع.
- صورة المنتج: اختياري قوي لتسريع التعرف عند البيع (قد تُخفى بسياسة الشاشة).
- التصنيف: مهم عملياً للترتيب والتقارير والتصفية.
- الماركة: مفيدة وخصوصاً للزيوت/الهيدروليك لتمييز العائلات.
- المخزن: مهم إن وُجدت مخازن متعددة — يحدد أين يُحسب الرصيد.
- نوع المخزون الأساسي: الأهم — يحدد شكل الكمية والتسعير (عدد / حجم / عائلة هيدروليك / عائلة زيت).
- المورد وكوده: اختياري تشغيلي لتسهيل الشراء وإعادة الطلب.
- الباركود: مسح سريع عند البيع إن كان الحقل ظاهراً.

③ الأنواع الأربعة الأساسية:
0) عدد (قطعة): كمية بالقطعة؛ تسعير على المنتج؛ كمية وتنبيه على البطاقة.
3) حجم (لتر — زيت مفرد): أساس باللتر؛ وحدات بيع إضافية؛ تسعير على المنتج.
4) هيدروليك — عائلة: ماركة + درجات وعبوات؛ الأسعار على جدول الدرجات.
5) زيت — عائلة: ماركة + لزوجات وعبوات؛ الأسعار على جدول اللزوجات.
(الوزن والملابس خيارات إضافية إن فُعّلت في الميزات — ليست ضمن الجولات الأساسية).

④ التسعير ثم إدارة المخزون: سعر شراء/بيع وحدود؛ تتبع المخزون والكمية والتنبيه.
''';

  static const identityPack = '''
حقول بطاقة «بيانات المنتج»:

• اسم المنتج (مهم إلزامي): هوية المنتج في البيع والبحث. خطأ شائع: اسم عام جداً يصعّب التمييز.
• SKU (عرض فقط): رمز داخلي تلقائي.
• الوصف (اختياري): يوضح المواصفات للموظفين/التقارير.
• صورة (اختياري قوي): تسرّع اختيار المنتج عند البيع.
• التصنيف (مهم عملياً): مجموعات للمنتجات؛ بدونه تصعب التصفية والتقارير.
• الماركة (مفيدة / شبه مهمة للزيوت): تربط عائلات الزيت والهيدروليك وتفرّق المنتجات المتشابهة.
• الرتبة/الجودة (مشروط بالسياسة): تظهر فقط إن فُعّلت درجات الجودة.
• المخزن (مهم مع تعدد المخازن): أين يُخزَّن الرصيد؛ مع مخزن واحد اختره أو اتركه حسب سياستك.
• نوع المخزون الأساسي (الأهم): يغيّر بقية النموذج (كمية، وحدات، درجات/لزوجات، مكان الأسعار).
• المورد + كود المورد (اختياري): لمشتريات أوضح وإعادة طلب أسهل.
• الباركود (مشروط): للمسح عند البيع.
''';

  static const stockKindsPack = '''
أنواع المخزون الأساسي — الأربعة العملية:

1) عدد (قطعة كأساس): للمنتجات المعدودة (فلتر، قطعة غيار، علبة جاهزة بالقطعة). الكمية قطعة؛ الأسعار على بطاقة التسعير؛ أدخل الكمية وتنبيه الحد الأدنى في إدارة المخزون.

2) حجم (لتر كأساس — زيت مفرد): لمنتج سائل واحد يُباع باللتر و/أو بعلبة عبر «وحدات إضافية». معامل التحويل يربط العلبة باللتر. التسعير على المنتج/الوحدات لا على جدول عائلة.

3) هيدروليك — عائلة: منتج أب (ماركة/عائلة) + درجات وعبوات متعددة. أسعار الشراء/البيع لكل درجة في الجدول؛ بطاقة التسعير الرئيسية تصبح تلميحاً فقط.

4) زيت — عائلة: مثل الهيدروليك لكن بلزوجات وعبوات زيت. اسم العائلة + صفوف اللزوجة والعبوات والأسعار في المحرر.

اختر النوع قبل ملء الكميات والأسعار لأن الحقول تتغيّر حسب الاختيار.
''';

  static const pricingPack = '''
بطاقة «التسعير»:

• سعر الشراء: تكلفة الحصول على الوحدة الأساسية (قطعة أو لتر).
• اقتراح البيع (إن ظهر): يساعد على هامش سريع من سعر الشراء.
• سعر البيع: ما يدفعه الزبون عند البيع العادي.
• الضريبة / الخصم: حسب سياسة المحل إن فُعّلت التسعيرة المتقدمة.
• أقل سعر بيع: يمنع البيع بأقل من حدك حتى لو خُفّض السعر يدوياً.
• هامش الربح: مؤشر توضيحي من الشراء والبيع.

لعائلات الزيت/الهيدروليك: لا تسعّر هنا — ضع الأسعار في جدول الدرجات/اللزوجات أعلاه.
''';

  static const inventoryPack = '''
بطاقة «إدارة المخزون»:

• تتبع المخزون (مهم): عند التشغيل يُخصم/يُزاد الرصيد مع البيع والشراء؛ عند الإيقاف لا تُسجَّل كميات.
• الكمية في المخزون: الرصيد الابتدائي (قطعة أو لتر حسب النوع) — لا تظهر بنفس الشكل لعائلات السوائل ذات الدرجات.
• تنبيه عند أقل من: يحذّرك قبل النفاد.
• حقول إضافية (إن ظهرت): وزن صافي، تواريخ إنتاج/انتهاء، ملاحظات داخلية، وسوم — للتقارير والجودة وليست شرط البيع اليومي.
''';

  static const packSnippet = overviewPack;

  static String? matchSnippet(String normalizedQuestion) {
    final q = normalizedQuestion;
    if (q.contains('عائله زيت') ||
        q.contains('عائلة زيت') ||
        q.contains('لزوج') ||
        (q.contains('زيت') && (q.contains('عائله') || q.contains('عائلة')))) {
      return '$stockKindsPack\n---\n$identityPack';
    }
    if (q.contains('هيدروليك') || q.contains('هدروليك')) {
      return '$stockKindsPack\n---\n$identityPack';
    }
    if (q.contains('تسعير') ||
        q.contains('سعر بيع') ||
        q.contains('سعر شراء') ||
        q.contains('هامش')) {
      return pricingPack;
    }
    if (q.contains('تتبع المخزون') ||
        q.contains('كميه في المخزون') ||
        q.contains('كمية في المخزون') ||
        q.contains('تنبيه عند') ||
        (q.contains('اداره المخزون') || q.contains('إدارة المخزون'))) {
      return inventoryPack;
    }
    if (q.contains('نوع المخزون') ||
        q.contains('بالعدد') ||
        (q.contains('حجم') && q.contains('لتر')) ||
        q.contains('قطعه') ||
        q.contains('قطعة')) {
      return stockKindsPack;
    }
    if (q.contains('منتج جديد') ||
        q.contains('اضيف منتج') ||
        q.contains('أضيف منتج') ||
        q.contains('اضافه منتج') ||
        q.contains('إضافة منتج') ||
        q.contains('اضيف بضاعه') ||
        q.contains('أضيف بضاعة') ||
        q.contains('كيف اضيف منتج') ||
        q.contains('كيف أضيف منتج') ||
        q.contains('شلون اضيف منتج') ||
        q.contains('شلون أضيف منتج') ||
        q.contains('بيانات المنتج') ||
        q.contains('تصنيف') && q.contains('منتج') ||
        q.contains('الماركه') ||
        q.contains('الماركة')) {
      return overviewPack;
    }
    return null;
  }
}
