  /// ثقة عالية كافية لتجاوز DeepSeek.
  static const highConfidence = 0.72;

  GuideIntentMatch? match(String raw) {
    final q = _normalize(raw);
    if (q.isEmpty) return null;

    _IntentEntry? best;
    var bestScore = 0.0;

    for (final e in _entries) {
      var hits = 0;
      for (final kw in e.keywords) {
        if (q.contains(_normalize(kw))) hits++;
      }
      if (hits == 0) continue;
      // أي تطابق قوي يكفي؛ تعدد المرادفات يرفع الثقة دون أن يقسم على طول القائمة.
      final score = (0.55 + hits * 0.18).clamp(0.0, 1.0);
      if (score > bestScore) {
        bestScore = score;
        best = e;
      }
    }

    if (best == null || bestScore < 0.35) return null;
    return GuideIntentMatch(
      tourId: best.tourId,
      reply: best.reply,
      confidence: bestScore.clamp(0.0, 1.0),
    );
  }

  static String _normalize(String s) {
    return s
        .trim()
        .toLowerCase()
        .replaceAll('أ', 'ا')
        .replaceAll('إ', 'ا')
        .replaceAll('آ', 'ا')
        .replaceAll('ة', 'ه')
        .replaceAll('ى', 'ي')
        .replaceAll(RegExp(r'\s+'), ' ');
  }
}

